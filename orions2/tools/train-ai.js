#!/usr/bin/env node
/* Orions 2 — offline AI trainer.
 *
 * Usage:
 *   node tools/train-ai.js <records.json|dir> [...more]
 *
 * Accepts:
 *   - a single record JSON (导出战报 / 存档导出的文件)
 *   - a bundle {"schema":"orions2-records/v1","records":[...]}
 *   - a directory containing any of the above
 *
 * Writes:
 *   - js/ai-learned.js  (weights consumed by the game at boot)
 *   - training-report.json (top biases for review)
 *
 * The weights only bias the heuristic scores (clamped to ±2.5), so training
 * can never produce illegal or absurd plays — it nudges card/ability choices
 * towards the ones that actually showed up in won games.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const trainer = require('../js/trainer.js');

function collect(inputs) {
  const files = [];
  for (const input of inputs) {
    const st = fs.statSync(input);
    if (st.isDirectory()) {
      for (const name of fs.readdirSync(input)) {
        if (name.endsWith('.json')) files.push(path.join(input, name));
      }
    } else {
      files.push(input);
    }
  }
  const records = [];
  for (const file of files) {
    let data;
    try { data = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (e) {
      console.warn('skip (bad json):', file);
      continue;
    }
    if (Array.isArray(data)) records.push(...data);
    else if (data && Array.isArray(data.records)) records.push(...data.records);
    else if (data && data.meta) records.push(data);
    else console.warn('skip (unknown shape):', file);
  }
  return records;
}

function main() {
  const inputs = process.argv.slice(2);
  if (!inputs.length) {
    console.error('usage: node tools/train-ai.js <records.json|dir> [...]');
    process.exit(1);
  }
  const records = collect(inputs);
  if (!records.length) {
    console.error('no usable records found.');
    process.exit(1);
  }
  const weights = trainer.train(records);
  const biasCount = Object.keys(weights.bias).length;
  if (!biasCount) {
    console.error('not enough data yet: every card needs at least ' + trainer.MIN_SAMPLES +
      ' recorded decisions. Play/import more duels and retry.');
    process.exit(2);
  }
  const banner = '/* AUTO-GENERATED by tools/train-ai.js — ' + weights.trainedAt +
    ' · ' + weights.games + ' games / ' + weights.decisions + ' decisions. Do not edit by hand. */\n' +
    '/* The file keeps the localStorage loader so a newer in-game training wins. */\n';
  const body = 'window.AI_LEARNED = ' + JSON.stringify(weights, null, 2) + ';\n' +
    'try { const __raw = localStorage.getItem("orions2.aiLearned.v1");' +
    ' if (__raw) { const __w = JSON.parse(__raw); if (__w && __w.bias) window.AI_LEARNED = __w; } } catch (e) {}\n' +
    'window.saveLearned = function (weights) { window.AI_LEARNED = weights;' +
    ' try { localStorage.setItem("orions2.aiLearned.v1", JSON.stringify(weights)); } catch (e) {} };\n';
  const out = path.join(__dirname, '..', 'js', 'ai-learned.js');
  fs.writeFileSync(out, banner + body);
  fs.writeFileSync(path.join(__dirname, '..', 'training-report.json'), JSON.stringify(weights, null, 2));

  console.log('trained on ' + weights.games + ' games, ' + weights.decisions + ' decisions.');
  console.log('wrote ' + out + ' (' + biasCount + ' weights)');
  console.log('\nstrongest biases:');
  for (const row of weights.top.slice(0, 12)) {
    console.log('  ' + row.key.padEnd(28) + ' bias ' + String(row.bias).padStart(6) +
      '  n=' + String(row.n).padStart(4) + '  winRate=' + row.winRate + '%');
  }
}

main();
